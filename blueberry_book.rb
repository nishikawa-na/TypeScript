文と式の基本
プログラムの計算をするのが式
プログラムの構造を定義し、計算に組み立てるもの
文式・・・関数を実行したいが、返り値はいらない場合に；をつける。

TSの基本的な値は、プリミティブとオブジェクト・・・プリミティブ型はそれ以上小さく出来ないデータの種類　string number など。
リテラル・・・〜を生みたすための式　
数字は整数と少数をまとめて、number型とする。number型は５３ビット（５３桁までいける）
2進数や8進数などの書き方もあるよ。

TS新しい数字の型・・・BigIntこれは、ビット数制限がない！が、処理速度がnumberの方が早い。
BigIntの型注釈は、bigintと書く。　変数の型決めに使える。
それと、そのものの数値をBingIntにするんなら、数値n と表示する。　
